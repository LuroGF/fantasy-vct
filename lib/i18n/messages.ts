export type MessageKey =
  | `nav.${keyof (typeof messages)["es"]["nav"]}`
  | `header.${keyof (typeof messages)["es"]["header"]}`
  | `landing.${keyof (typeof messages)["es"]["landing"]}`
  | `auth.${keyof (typeof messages)["es"]["auth"]}`
  | `dashboard.${keyof (typeof messages)["es"]["dashboard"]}`
  | `leagues.${keyof (typeof messages)["es"]["leagues"]}`
  | `team.${keyof (typeof messages)["es"]["team"]}`;

export function translateMessage(
  locale: Locale,
  key: MessageKey,
  variables: Record<string, string | number> = {},
) {
  const [group, name] = key.split(".") as [keyof (typeof messages)["es"], string];
  const groupMessages = messages[locale][group] as Record<string, string>;
  const fallbackMessages = messages.es[group] as Record<string, string>;
  const template = groupMessages[name] || fallbackMessages[name] || key;
  return Object.entries(variables).reduce(
    (result, [variable, value]) => result.replaceAll(`{${variable}}`, String(value)),
    template,
  );
}
